import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
const {chromium} = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.PLOTTO_URL || 'http://127.0.0.1:8765';
const browser = await chromium.launch({headless: true});
await mkdir('test-results', {recursive: true});
try {
  const page = await browser.newPage({viewport: {width: 1360, height: 1000}});
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto(base, {waitUntil: 'domcontentloaded'});
  await page.locator('#outline[aria-busy="false"] .main-stage .story-text').waitFor();
  await page.locator('summary').filter({hasText: 'Shape the masterplot'}).click();
  await page.locator('#protagonist').selectOption('6');
  await page.locator('#ending').selectOption('9');
  await page.locator('summary').filter({hasText: 'Names & a starting conflict'}).click();
  await page.locator('#start-conflict').fill('813');
  await page.locator('#generate').click();
  assert.match(await page.locator('.masterplot-sentence').innerText(), /^A Protecting Person, being impelled/);
  assert.match(await page.locator('.masterplot-sentence').innerText(), /achieves success and happiness/);
  assert.match(await page.locator('.masterplot-connection').innerText(), /881 under C9/);
  assert.deepEqual(await page.locator('.masterplot .clause-letter').allTextContents(), ['A6', 'B50', 'C9']);
  assert.equal(await page.locator('#character-names #name-a').isVisible(), true);
  assert.equal(await page.locator('#character-names #name-b').isVisible(), true);
  assert.equal(await page.locator('#character-names #name-SN').isVisible(), true);
  assert.equal(await page.locator('#outline #name-SN').count(), 0);
  await page.locator('#name-SN').fill('Alex');
  assert.match(await page.locator('.main-stage .story-text').innerText(), /son, Alex,/);
  await page.locator('#character-names').screenshot({path: 'test-results/grouped-character-names.png'});
  await page.locator('.masterplot').screenshot({path: 'test-results/masterplot-indexed.png'});
  await page.locator('#ending').selectOption('8');
  await page.locator('#generate').click();
  assert.match(await page.locator('.masterplot-connection').innerText(), /C8 is a planned outcome/);
  await page.locator('#protagonist').selectOption('');
  await page.locator('#ending').selectOption('');
  await page.locator('#action').selectOption('62');
  await page.locator('#generate').click();
  const ids = await page.locator('.masterplot .clause-letter').allTextContents();
  assert.equal(ids[0], 'A15');
  assert.equal(ids[1], 'B62');
  const snapshot = await page.locator('#outline-content').innerText();
  await page.reload({waitUntil: 'domcontentloaded'});
  await page.locator('#outline[aria-busy="false"] .main-stage .story-text').waitFor();
  assert.equal(await page.locator('#outline-content').innerText(), snapshot);
  await page.getByRole('link', {name: 'Name characters'}).click();
  assert.equal(await page.locator('#character-names').evaluate((details) => details.open), true);
  assert.equal(await page.locator('#name-SN').inputValue(), 'Alex');
  await page.setViewportSize({width: 390, height: 844});
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.locator('#character-names').screenshot({path: 'test-results/grouped-character-names-mobile.png'});
  assert.deepEqual(errors, []);
  console.log('Masterplot checks passed: A/B/C sentence and ids, indexed vs planned endings, B62, grouped names, saved choices and mobile layout.');
} finally { await browser.close(); }
