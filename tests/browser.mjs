// Optional browser qualification. Set PLAYWRIGHT_MODULE to a local Playwright module,
// or install Playwright before running: node tests/browser.mjs.
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
const {chromium} = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.PLOTTO_URL || 'http://127.0.0.1:8765';
const browser = await chromium.launch({headless: true});
const context = await browser.newContext({viewport: {width: 1360, height: 1000}, permissions: ['clipboard-read', 'clipboard-write']});
const page = await context.newPage();
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
const localFailures = [];
page.on('response', (response) => {
  if (response.url().startsWith(base) && response.status() >= 400 && !response.url().endsWith('/favicon.ico')) {
    localFailures.push(`${response.status()} ${response.url()}`);
  }
});
const ready = async (p = page) => {
  await p.locator('#outline[aria-busy="false"] .main-stage .story-text').waitFor();
};
const main = (p = page) => p.locator('.main-stage .story-text');
const snapshot = (p = page) => p.locator('#outline-content').innerText();
await mkdir('test-results', {recursive: true});
try {
  await page.goto(base, {waitUntil: 'domcontentloaded'});
  await ready();
  assert.equal(await page.locator('.story-stage').count(), 3);
  assert.equal(await page.locator('#generate').isEnabled(), true);
  await page.locator('summary').filter({hasText: 'Names & a starting conflict'}).click();
  await page.locator('#start-conflict').fill('542');
  await page.locator('#name-a').fill('Márta');
  await page.locator('#name-b').fill('Sam');
  await page.locator('#generate').click();
  await page.locator('.main-stage .story-ref[href$="#542"]').waitFor();
  assert.match(await main().innerText(), /^Márta/);
  assert.match(await main().innerText(), /Sam/);
  const fixedMain = await main().innerText();
  const master = await page.locator('.masterplot').innerText();
  await page.locator('#before-reroll').click();
  assert.equal(await main().innerText(), fixedMain);
  assert.equal(await page.locator('.masterplot').innerText(), master);
  await page.locator('#after-reroll').click();
  assert.equal(await main().innerText(), fixedMain);
  await page.locator('#edition').selectOption('fm');
  await page.locator('.main-stage .story-text').filter({hasText: 'her husband'}).waitFor();
  assert.match(await main().innerText(), /^Márta/);
  await page.locator('#copy-outline').click();
  await page.waitForFunction(() => document.getElementById('status').textContent === 'Outline copied.');
  const copiedText = await page.evaluate(() => navigator.clipboard.readText());
  assert.match(copiedText, /\[542\] Márta/);
  assert.match(copiedText, /Edition: A=female, B=male/);
  await page.locator('#copy-link').click();
  await page.waitForFunction(() => document.getElementById('status').textContent.startsWith('Link copied.'));
  const sharedUrl = await page.evaluate(() => navigator.clipboard.readText());
  assert.match(sharedUrl, /#outline=/);
  const sharedSnapshot = await snapshot();
  const restored = await context.newPage();
  await restored.goto(sharedUrl, {waitUntil: 'domcontentloaded'});
  await ready(restored);
  assert.equal(await snapshot(restored), sharedSnapshot);
  assert.equal(await restored.locator('#name-a').inputValue(), 'Márta');
  await restored.close();
  const download = page.waitForEvent('download');
  await page.locator('#download-outline').click();
  assert.equal((await download).suggestedFilename(), 'plotto-542.txt');
  await page.evaluate(() => { navigator.clipboard.writeText = async () => { throw new Error('denied'); }; });
  await page.locator('#copy-outline').click();
  await page.locator('#copy-fallback:visible').waitFor();
  assert.match(await page.locator('#copy-fallback').inputValue(), /\[542\] Márta/);
  await page.locator('#start-conflict').fill('1463');
  await page.locator('#generate').click();
  assert.match(await page.locator('#error').innerText(), /1 to 1462/);
  assert.equal(await main().innerText(), fixedMain.replace('his wife', 'her husband'));
  await page.locator('#search').fill('542');
  assert.equal(await page.locator('.conflict-result').count(), 1);
  await page.locator('.conflict-result button').click();
  assert.match(await page.locator('#status').innerText(), /542/);
  await page.locator('#search').fill('secret');
  assert.ok(await page.locator('.conflict-result').count() > 0);
  await page.locator('#search').fill('542');
  await page.locator('#browse-theme').selectOption('Enterprise');
  assert.equal(await page.locator('.conflict-result').count(), 0);
  assert.match(await page.locator('#result-count').innerText(), /No conflicts found/);
  await page.locator('#browse-theme').selectOption('');
  await page.locator('#search').fill('');
  assert.equal(await page.locator('.conflict-result').count(), 12);
  await page.locator('#more-results').click();
  assert.equal(await page.locator('.conflict-result').count(), 24);
  // Test the real shared-header controls when its remote enhancement is available.
  const dark = page.locator('tedt-global-header').getByRole('button', {name: 'Dark', exact: true});
  if (await dark.count()) {
    await dark.click();
    await page.waitForFunction(() => document.documentElement.dataset.theme === 'dark');
    await page.locator('tedt-global-header').getByRole('button', {name: 'Light', exact: true}).click();
    await page.waitForFunction(() => document.documentElement.dataset.theme === 'light');
  }
  await page.locator('#workbench').scrollIntoViewIfNeeded();
  await page.screenshot({path: 'test-results/desktop.png', fullPage: false});
  await page.evaluate(() => { document.documentElement.dataset.theme = 'dark'; document.documentElement.dataset.bsTheme = 'dark'; });
  await page.screenshot({path: 'test-results/desktop-dark.png', fullPage: false});
  await page.setViewportSize({width: 390, height: 844});
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({path: 'test-results/mobile-dark.png', fullPage: true});
  await page.evaluate(() => { document.documentElement.dataset.theme = 'light'; document.documentElement.dataset.bsTheme = 'light'; });
  await page.screenshot({path: 'test-results/mobile.png', fullPage: true});
  await page.locator('.main-stage .story-ref').click();
  await page.waitForURL('**/plotto-fm.html#542');
  assert.match(await page.locator('#\\35 42 .desc').innerText(), /her husband/);
  await page.locator('#book-random').click();
  assert.match(new URL(page.url()).hash, /^#\d+$/);
  const hash = new URL(page.url()).hash;
  await page.locator('a[data-edition-link][href^="plotto-mf"]').click();
  await page.waitForURL(`**/plotto-mf.html${hash}`);
  await page.goto(`${base}/how-to.html`, {waitUntil: 'domcontentloaded'});
  assert.equal(await page.locator('h1').innerText(), 'How to use Plotto');
  await page.goto(base, {waitUntil: 'domcontentloaded'});
  await ready();
  await page.locator('summary').filter({hasText: 'Names & a starting conflict'}).click();
  await page.locator('#start-conflict').fill('75a');
  await page.locator('#generate').click();
  const alternatives = page.locator('#after-choice');
  await alternatives.locator('xpath=ancestor::details').locator('summary').click();
  const repaired = await alternatives.locator('option').evaluateAll((options) => options.find((option) => option.textContent === '1267a').value);
  await alternatives.selectOption(repaired);
  const evidenceLink = page.locator('a[href="corrections.html#ref-75a-after"]');
  await evidenceLink.waitFor();
  assert.match(await page.locator('[aria-labelledby="after-heading"]').innerText(), /Editorial repair: the book prints 1267d/);
  await evidenceLink.click();
  await page.waitForURL('**/corrections.html#ref-75a-after');
  assert.equal(await page.locator('.correction-entry').count(), 24);
  assert.match(await page.locator('#ref-75a-after').innerText(), /editorial choice, not a recovered variant d/);
  await page.locator('#ref-75a-after a[href="plotto-mf.html#75a"]').click();
  await page.waitForURL('**/plotto-mf.html#75a');
  const repairedBookLink = page.locator('.conflict[id="75"] .postlinks a[href="#1267a"]');
  assert.match(await repairedBookLink.getAttribute('aria-label'), /editorial repair; printed 1267d/);
  await repairedBookLink.click();
  await page.waitForURL('**/plotto-mf.html#1267a');
  await page.goto(`${base}/#outline=%7Bbroken`, {waitUntil: 'domcontentloaded'});
  await ready();
  assert.match(await page.locator('#error').innerText(), /shared outline could not be opened/);
  // A dataset failure has a usable recovery control and keeps export unavailable.
  const recovery = await context.newPage();
  await recovery.route('**/data/plotto-mf.json', (route) => route.fulfill({status: 503, body: 'unavailable'}));
  await recovery.goto(base, {waitUntil: 'domcontentloaded'});
  await recovery.locator('#retry:visible').waitFor();
  assert.equal(await recovery.locator('#export-tools').isVisible(), false);
  await recovery.unroute('**/data/plotto-mf.json');
  await recovery.locator('#retry').click();
  await ready(recovery);
  await recovery.route('**/data/plotto-fm.json', (route) => route.fulfill({status: 503, body: 'unavailable'}));
  await recovery.locator('#edition').selectOption('fm');
  await recovery.locator('#retry:visible').waitFor();
  assert.equal(await recovery.locator('#export-tools').isVisible(), false);
  assert.equal(await recovery.locator('#generate').isEnabled(), false);
  assert.equal(await recovery.locator('#edition').isEnabled(), true);
  await recovery.locator('#edition').selectOption('mf');
  await ready(recovery);
  await recovery.close();
  const noJs = await browser.newContext({javaScriptEnabled: false});
  const reader = await noJs.newPage();
  await reader.goto(`${base}/plotto-mf.html#542`, {waitUntil: 'domcontentloaded'});
  assert.equal(await reader.locator('.conflict').count(), 1462);
  assert.equal(await reader.locator('#book-random').isVisible(), false);
  await reader.locator('.book-nav a[href="./"]').waitFor();
  await noJs.close();
  assert.deepEqual(localFailures, []);
  assert.deepEqual(errors, []);
  console.log('Browser checks passed: generation, rerolls, both editions, Unicode names, copy/fallback, exact share restore, download, validation, search, pagination, reader links, mobile layout, malformed links, fetch retry and no-JavaScript book access.');
} finally {
  await browser.close();
}
